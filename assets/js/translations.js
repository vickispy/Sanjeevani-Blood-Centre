/**
 * Translation Controller
 */
const I18n = {
  currentLang: "en",

  init() {
    // Retrieve stored language or default to en
    const stored = localStorage.getItem("sanjeevani_lang");
    if (stored && (stored === "en" || stored === "mr" || stored === "hi")) {
      this.currentLang = stored;
    }
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  },

  setLanguage(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem("sanjeevani_lang", lang);
    this.applyLanguage(lang);
  },

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    
    // Update all elements with data-i18n attribute
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = TRANSLATIONS[lang]?.[key] || TRANSLATIONS["en"]?.[key];
      if (translation) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = translation;
        } else {
          const childSpan = el.querySelector("span[data-i18n]") || el.querySelector("span");
          if (childSpan && childSpan !== el) {
            childSpan.textContent = translation;
          } else if (el.querySelector("i, svg")) {
            let updated = false;
            for (let i = el.childNodes.length - 1; i >= 0; i--) {
              if (el.childNodes[i].nodeType === 3) {
                el.childNodes[i].nodeValue = " " + translation;
                updated = true;
                break;
              }
            }
            if (!updated) el.appendChild(document.createTextNode(" " + translation));
          } else {
            el.textContent = translation;
          }
        }
      }
    });

    // Update active state in language selector UI
    const langBtns = document.querySelectorAll(".lang-option");
    langBtns.forEach(btn => {
      if (btn.getAttribute("data-lang") === lang) {
        btn.classList.add("active");
        btn.setAttribute("aria-selected", "true");
      } else {
        btn.classList.remove("active");
        btn.setAttribute("aria-selected", "false");
      }
    });

    // Update main language button text
    const currentLangLabel = document.getElementById("currentLangLabel");
    if (currentLangLabel) {
      const labels = { en: "English", mr: "मराठी", hi: "हिंदी" };
      currentLangLabel.textContent = labels[lang] || "English";
    }
  },

  bindEvents() {
    const trigger = document.getElementById("langSelectorBtn");
    const dropdown = document.getElementById("langDropdown");
    
    if (trigger && dropdown) {
      trigger.addEventListener("click", (e) => {
        e.stopPropagation();
        const isOpen = dropdown.classList.contains("is-open");
        dropdown.classList.toggle("is-open", !isOpen);
        trigger.setAttribute("aria-expanded", String(!isOpen));
      });

      document.addEventListener("click", () => {
        dropdown.classList.remove("is-open");
        trigger.setAttribute("aria-expanded", "false");
      });
    }

    // Option clicks
    const options = document.querySelectorAll(".lang-option");
    options.forEach(opt => {
      opt.addEventListener("click", (e) => {
        const selected = opt.getAttribute("data-lang");
        this.setLanguage(selected);
        if (dropdown) dropdown.classList.remove("is-open");
        if (trigger) trigger.setAttribute("aria-expanded", "false");
      });
    });
  }
};
